export function paperFor(item) {
  if (item.isDir) return KINDS.folder;
  const ext = (item.ext || "").toLowerCase();
  const name = (item.name || "").toLowerCase();

  // 彩蛋 4：黑客帝国幽绿代码雨 (Matrix Stream)
  // 拖入代码文件或文件名带 matrix/hack/cyber/payload 时触发专属幽绿代码雨彩蛋！
  if (CODE_EXTS.has(ext) || name.includes("matrix") || name.includes("hack") || name.includes("cyber")) {
    return KINDS.matrix;
  }

  const paper = KINDS[EXT[ext] || "notes"];
  const accent = ACCENT[ext];
  if (!accent) return paper;
  return { ...paper, accent: accent[0], ink: accent[1] };
}
